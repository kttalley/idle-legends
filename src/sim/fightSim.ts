/** A reproducible mob — what an ambient hero actually fights in L0. */
export function makeMob(seed: number, level: number, name = 'Sim Beast'): MobInstance {
  const rng = mulberry32(seed)
  const maxHp = Math.round(60 + level * 22 * (0.8 + rng() * 0.4))
  return {
    id: `sim_mob_${seed}`,
    templateId: 'sim' as MobInstance['templateId'],
    name,
    baseName: name,
    attackAccum: 0,
    currentHp: maxHp,
    maxHp,
    damage: Math.round(4 + level * 1.6 * (0.8 + rng() * 0.4)),
    xpReward: 0,
    goldMin: 0,
    goldMax: 0,
    lootTableIds: [],
    spriteKey: 'beast',
    attackSpeedSeconds: 2,
    isElite: false,
    isBoss: false,
    offset: { dx: 0, dy: 0 },
    dots: [],
    ...combatantOnlyWorldFields(),
  }
}

export interface DeterminismCase {
  label: string
  seed: number
  run: () => FightResult
}

export interface DeterminismReport {
  label: string
  seed: number
  identical: boolean
  events: number
  winner: 0 | 1 | null
  duration: number
  /** First differing line, when a case fails. */
  firstDiff?: string
}

/** Run a case twice from scratch and compare the serialised logs byte for byte. */
export function checkDeterminism(c: DeterminismCase): DeterminismReport {
  const a = formatFightLog(c.run())
  const b = formatFightLog(c.run())
  const result = c.run()

  let firstDiff: string | undefined
  if (a !== b) {
    const la = a.split('\n'), lb = b.split('\n')
    for (let i = 0; i < Math.max(la.length, lb.length); i++) {
      if (la[i] !== lb[i]) { firstDiff = `line ${i + 1}:\n  run1: ${la[i] ?? '<eof>'}\n  run2: ${lb[i] ?? '<eof>'}`; break }
    }
  }

  return {
    label: c.label,
    seed: c.seed,
    identical: a === b,
    events: result.events.length,
    winner: result.winner,
    duration: result.duration,
    firstDiff,
  }
}

/**
 * The counter-test. A resolver that ignored its seed entirely — or one whose rolls got
 * stubbed to a constant — would sail through `checkDeterminism`, because a frozen fight
 * is trivially reproducible. So: distinct seeds must produce distinct fights.
 *
 * The bar is a THRESHOLD, not perfection, and that is not a fudge. A short fight
 * contains few rolls — a talentless warrior rolls once per swing (crit) over ~8 swings —
 * so two seeds landing the same crit pattern is ordinary birthday-paradox collision, not
 * a desync. Demanding 100% uniqueness there fails a perfectly correct engine. Feed this
 * a proc-rich fight (`standardCases`' duel) and keep the threshold below 1.
 */
export function checkSeedSensitivity(
  make: (seed: number) => FightResult,
  seeds: number[],
  minDistinctRatio = 0.9,
): { distinct: number; total: number; ratio: number; pass: boolean; collisions: string[] } {
  const seen = new Map<string, number>()
  const collisions: string[] = []
  for (const s of seeds) {
    const log = formatFightLog(make(s))
    // Compare on the body, not the header — the header embeds the seed, so two
    // identical fights under different seeds would otherwise look distinct.
    const body = log.split('\n').slice(1).join('\n')
    const prior = seen.get(body)
    if (prior !== undefined) collisions.push(`seed ${s} produced the same log as seed ${prior}`)
    else seen.set(body, s)
  }
  const ratio = seen.size / seeds.length
  return { distinct: seen.size, total: seeds.length, ratio, pass: ratio >= minDistinctRatio, collisions }
}

const CLASSES: ClassType[] = ['warrior', 'mage', 'rogue', 'warlock']

/** The standard suite: hero-vs-mob (Track L) and hero-vs-hero (Track P) across classes. */
export function standardCases(seeds: number[]): DeterminismCase[] {
  const cases: DeterminismCase[] = []
  for (const seed of seeds) {
    for (const cls of CLASSES) {
      cases.push({
        label: `${cls} vs mob`,
        seed,
        run: () => runFight(seed, makeRoster(seed + 1, cls, 30, `H${cls}`), makeMob(seed + 2, 30)),
      })
    }
    cases.push({
      label: 'warrior vs mage (duel)',
      seed,
      run: () => runFight(
        seed,
        makeRoster(seed + 11, 'warrior', 40, 'Concord'),
        makeRoster(seed + 22, 'mage', 40, 'Ashmarch'),
      ),
    })
  }

  // ── Talented cases, APPENDED ────────────────────────────────────────────────
  // Deliberately after the whole untalented loop rather than interleaved into it. The
  // golden is a line-ordered artefact, so inserting these per-seed would shift every
  // existing line and the diff would read as "the entire baseline changed" — hiding a
  // real regression inside a wall of noise. Appended, the diff is provably pure ADDITION
  // and every pre-existing block stays byte-identical.
  for (const seed of seeds) {
    for (const b of TALENT_BUILDS) {
      cases.push({
        label: `${b.label} vs mob`,
        seed,
        run: () => runFight(
          seed,
          makeRoster(seed + 3, b.cls, 30, `T${b.cls}`, b.allocs),
          makeMob(seed + 4, 30),
        ),
      })
    }
    // A talented duel: hero-vs-hero is the only shape where a DEFENDER's talents matter
    // (block, damage reduction, thorns), because a mob has none.
    cases.push({
      label: 'talented duel (procs vs defence)',
      seed,
      run: () => runFight(
        seed,
        makeRoster(seed + 33, 'warrior', 40, 'Procs', TALENT_BUILDS[0].allocs),
        makeRoster(seed + 44, 'warrior', 40, 'Wall', TALENT_BUILDS[1].allocs),
      ),
    })
  }
  return cases
}

// ── The golden log ────────────────────────────────────────────────────────────
//
// `checkDeterminism` compares a case against ITSELF, twice, inside one process. That
// proves the fight is reproducible; it proves nothing about whether the fight still
// resolves the way it did yesterday. Change the RNG draw order — which is exactly what
// widening the loop from two combatants to N does — and every case still agrees with its
// own re-run, so the suite goes on reporting PASS while no longer covering the thing that
// changed. The failure mode is silent, which is the worst kind.
//
// So: a committed artefact of what the resolver produces TODAY, byte for byte. A
// behaviour change must then either preserve it or explicitly rewrite it, and rewriting
// it is a reviewable diff rather than an invisible non-event.
//
// Seeds are pinned here rather than taken from `--seeds`, because a golden file whose
// contents depend on a command-line flag is not a baseline.

export const GOLDEN_SEEDS = [1000, 8717, 16434, 24151, 31868, 39585]

/** Serialise the whole standard suite into one comparable artefact. */
export function formatGolden(cases: DeterminismCase[]): string {
  const out: string[] = [
    '# Stillmarch — fight resolver golden log',
    '# Regenerate with: node tools/sim/fight.mjs --update-golden',
    '# A diff here is a COMBAT BEHAVIOUR CHANGE. Read it before accepting it.',
    '',
  ]
  for (const c of cases) {
    out.push(`## ${c.label} | seed=${c.seed}`)
    out.push(formatFightLog(c.run()))
    out.push('')
  }
  return out.join('\n')
}

export interface GoldenReport {
  matched: boolean
  /** Null when there is no committed baseline yet. */
  missing: boolean
  totalLines: number
  diffLines: number
  /** First divergence, rendered for a terminal. */
  firstDiff?: string
}

export function compareGolden(expected: string | null, actual: string): GoldenReport {
  const actualLines = actual.split('\n')
  if (expected === null) {
    return { matched: false, missing: true, totalLines: actualLines.length, diffLines: 0 }
  }
  if (expected === actual) {
    return { matched: true, missing: false, totalLines: actualLines.length, diffLines: 0 }
  }

  const exp = expected.split('\n')
  let firstDiff: string | undefined
  let diffLines = 0
  for (let i = 0; i < Math.max(exp.length, actualLines.length); i++) {
    if (exp[i] === actualLines[i]) continue
    diffLines++
    if (firstDiff) continue
    // Carry the nearest preceding case header, or a bare line number is unreadable.
    let ctx = ''
    for (let k = i; k >= 0; k--) {
      if (exp[k]?.startsWith('## ')) { ctx = exp[k]; break }
    }
    firstDiff =
      `line ${i + 1}${ctx ? `  (in ${ctx.slice(3)})` : ''}\n` +
      `  golden: ${exp[i] ?? '<eof>'}\n` +
      `  now:    ${actualLines[i] ?? '<eof>'}`
  }
  return { matched: false, missing: false, totalLines: actualLines.length, diffLines, firstDiff }
}

export function formatGoldenReport(r: GoldenReport): string {
  const lines = ['── Golden log ────────────────────────────────────────────────────']
  if (r.missing) {
    lines.push('NO BASELINE — run with --update-golden to record one.')
    return lines.join('\n')
  }
  if (r.matched) {
    lines.push(`matched: ${r.totalLines} lines byte-identical to the committed baseline`)
    return lines.join('\n')
  }
  lines.push(`CHANGED — ${r.diffLines} line(s) differ from the committed baseline`)
  lines.push('')
  lines.push(r.firstDiff ?? '  (baseline and current differ in length only)')
  lines.push('')
  lines.push('If this change is intended, regenerate with --update-golden and')
  lines.push('review the resulting diff as part of the change.')
  return lines.join('\n')
}

export function formatDeterminismReport(rs: DeterminismReport[]): string {
  const fails = rs.filter(r => !r.identical)
  const lines: string[] = []
  lines.push('── Fight determinism ─────────────────────────────────────────────')
  lines.push(`cases: ${rs.length}   identical: ${rs.length - fails.length}   FAILED: ${fails.length}`)
  lines.push('')
  lines.push('  seed  case                      events  winner  dur    result')
  for (const r of rs) {
    lines.push(
      `  ${String(r.seed).padStart(4)}  ${r.label.padEnd(24)}  ` +
      `${String(r.events).padStart(6)}  ${String(r.winner).padStart(6)}  ` +
      `${r.duration.toFixed(1).padStart(5)}  ${r.identical ? 'ok' : 'DESYNC'}`,
    )
  }
  for (const f of fails) {
    lines.push('')
    lines.push(`DESYNC — ${f.label} (seed ${f.seed}):`)
    lines.push(f.firstDiff ?? '  (logs differ in length only)')
  }
  return lines.join('\n')
}
