// Determinism harness for the headless fight resolver.
//
// This is the acceptance test for Track P step 0: **the same seed and the same two
// roster snapshots must produce a byte-identical fight log, twice.** Without it, ghost
// PvP is built on sand — a desync would only show up after rosters were live.
//
// Two things this deliberately does NOT do:
//
//  - It does not install a seeded global `Math.random`. `tools/sim/run.mjs` does that
//    for the economy harness, and it would make this test pass vacuously. The point is
//    that the fight is deterministic *because the seed is threaded through it*, not
//    because the whole process was pinned.
//  - It does not accept "same winner" as a pass. Two runs can agree on the winner and
//    still have diverged on every roll in between. Only the full log counts.

import type { ClassType, Item, MobInstance, Slot, StatBonuses } from '../data/types'
import { formatFightLog, runFight, type FightResult, type HeroCombatant } from '../engine/fight'
import { combatantOnlyWorldFields } from '../engine/mobBehaviour'
import { mulberry32, type Rng } from '../engine/rng'

const SLOTS: Slot[] = ['weapon', 'helm', 'chest', 'legs', 'boots', 'trinket']

/** A deterministic stand-in for a roster snapshot: gear derived from the seed alone. */
function rosterEquipment(rng: Rng, level: number): Record<Slot, Item | null> {
  const eq = {} as Record<Slot, Item | null>
  for (const slot of SLOTS) {
    const power = 1 + Math.floor(rng() * level)
    const bonuses: StatBonuses = {
      strength: Math.round(power * (0.5 + rng())),
      intellect: Math.round(power * (0.5 + rng())),
      agility: Math.round(power * (0.5 + rng())),
      stamina: Math.round(power * (1 + rng())),
      armor: Math.round(power * (0.5 + rng())),
      weaponDps: slot === 'weapon' ? Math.round(power * (2 + rng() * 2)) : 0,
      critChance: +(rng() * 0.03).toFixed(4),
    }
    eq[slot] = {
      id: `sim_${slot}_${level}`,
      name: `Sim ${slot}`,
      slot,
      rarity: 'common',
      level,
      statBonuses: bonuses,
      vendorValue: 0,
    }
  }
  return eq
}

/** Build a reproducible hero from a seed — stands in for a downloaded PvP snapshot. */
export function makeRoster(
  seed: number, playerClass: ClassType, level: number, name: string,
  /** Talent build. Empty by default, which is what every ORIGINAL golden case uses —
   *  changing that default would rewrite the whole committed baseline. */
  talentAllocs: Record<string, number> = {},
): HeroCombatant {
  const rng = mulberry32(seed)
  return {
    name,
    playerClass,
    level,
    equipment: rosterEquipment(rng, level),
    talentAllocs,
    racialPassive: {},
  }
}

// ── Talent builds that force specific draw sites to fire ──────────────────────
//
// The baseline used to allocate NOTHING (`const allocs = {}` for every roster), and the
// consequence was worse than "thin coverage": with no talents, every talent-gated roll
// short-circuits BEFORE calling rng(). `vilePoisons` is null, `swordSpecEnabled` false,
// `flurryChance` 0, `avoidChance` 0 — so the entire committed golden exercised exactly one
// draw site, the hero crit roll (combat.ts:359). Measured event mix in the old file: 382
// `swing`, 30 `death`, and zero each of `dot`, `block`, `thorns`, `extra`, `flurry`.
//
// That made the golden blind to nearly every change C5 wants to make. Adopting recursive
// extra/flurry, changing DoT stacking from append to refresh, passing the real
// `mobAttackSpeedFactor` instead of a literal 1 — all of them would have left the file
// byte-identical and sailed through as a PASS.
//
// Builds are HAND-PINNED rather than generated by `allocateSpec`. Generated allocations
// are deterministic too, but they are chosen for plausibility, not coverage: a retune of
// the allocation heuristic could quietly stop a mechanic firing and the golden would
// simply stop testing it, silently, which is the failure mode this whole file exists to
// prevent. Pinned ids say what they cover.
