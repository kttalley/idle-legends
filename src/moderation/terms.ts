/** True when the CURRENT version of the terms has been accepted on this device. */
export function termsAccepted(): boolean {
  try {
    return Number(localStorage.getItem(KEY)) >= TERMS_VERSION
  } catch {
    // Private-mode or a wedged storage quota. Failing CLOSED (treating it as not accepted)
    // would trap the player behind a gate whose acceptance can never be recorded — an
    // unplayable app. Failing open shows the gate again next launch, which is a nuisance
    // and nothing worse.
    return true
  }
}

/** Record acceptance. */
export function acceptTerms(): void {
  try {
    localStorage.setItem(KEY, String(TERMS_VERSION))
  } catch {
    // See above: an unrecordable acceptance must not block play.
  }
}
