// ── The EULA, and whether it has been agreed ──────────────────────────────────
//
// App Review 1.2 requires "that users agree to terms (EULA) and these terms must make it
// clear that there is no tolerance for objectionable content or abusive users", presented
// "before registering or logging in".
//
// Stillmarch has no registration screen — the Supabase session is created anonymously and
// invisibly the first time the cloud is touched (`net/session.ts`). "Before logging in"
// therefore means before the app does anything at all, which is why `TermsGate` sits ahead
// of character select rather than inside character creation. It is also the easiest thing
// to demonstrate in the screen recording Apple asked for: launch, and there it is.
//
// ── Why the text is compiled in rather than fetched ──────────────────────────
// A terms screen that needs the network to render is a terms screen that can fail to
// render, and this one gates the whole app. It also has to be identical to what the player
// agreed to, which a live-edited remote document is not.

/**
 * Bump when the terms MATERIALLY change, and only then.
 *
 * Acceptance is stored against this version, so incrementing it re-prompts every existing
 * player. That is the correct behaviour for a change to what they agreed to, and an
 * intolerable one for a typo fix — a re-consent wall on launch is a hostile thing to show
 * someone over a corrected comma.
 */
export const TERMS_VERSION = 1

const KEY = 'stillmarch.terms.accepted'

/**
 * Which store the purchase clause should name. Read lazily off the Capacitor global the
 * native WebView injects rather than an import from @capacitor/core, so this module stays
 * loadable anywhere (the Node harnesses read TERMS_SUMMARY's siblings). Not part of the
 * accepted-version contract: the policy is identical on every platform, only the store
 * named in it differs, so no TERMS_VERSION bump.
 */
function purchasePlatform(): 'ios' | 'android' | 'web' {
  if (typeof window === 'undefined') return 'web'
  const cap = (window as { Capacitor?: { getPlatform?: () => string } }).Capacitor
  const p = cap?.getPlatform?.()
  return p === 'ios' || p === 'android' ? p : 'web'
}

